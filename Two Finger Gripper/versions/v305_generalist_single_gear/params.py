#!/usr/bin/env python3
"""Version 2.4's parameters: params.json is the one source. values() reads it (plus overrides, clamped to each slider's
range); write_scad() writes params.scad, which gripper.scad includes. Run it to regenerate params.scad after editing
params.json; export_models.py does that too."""
from pathlib import Path
import json, math, sys
HERE=Path(__file__).resolve().parent


def specs():
    return [p for g in json.loads((HERE/'params.json').read_text())['groups'] for p in g['params']]


def values(overrides=None):
    """name -> value. Overrides must name a slider param (not calibration) and be a finite number; they are clamped to
    [min, max] and snapped to whole numbers where the step is."""
    out={p['name']:p['value'] for p in specs()};by={p['name']:p for p in specs()}
    for k,v in (overrides or {}).items():
        p=by.get(k)
        if p is None or p['stage']=='calibration':raise ValueError(f'not a tunable parameter: {k}')
        if isinstance(v,bool) or not isinstance(v,(int,float)) or not math.isfinite(v):raise ValueError(f'{k} must be a number')
        v=min(max(v,p['min']),p['max'])
        out[k]=int(round(v)) if float(p['step']).is_integer() and float(p['value']).is_integer() else float(v)
    return out


def outline_changed(overrides):
    """True when an override moves the plan outline, so trace_photo.py must run again."""
    stage={p['name']:p['stage'] for p in specs()};base=values()
    return any(stage[k]=='outline' and v!=base[k] for k,v in values(overrides).items())


def write_scad(path=HERE/'params.scad',vals=None):
    vals=vals or values();doc={p['name']:p for p in specs()}
    lines=['// GENERATED by params.py from params.json. Do not edit; change params.json and re-run params.py.']
    for k,v in vals.items():
        p=doc[k];unit=f' ({p["unit"]})' if p['unit'] else ''
        lines.append(f'{k}={json.dumps(v)};'.ljust(28)+f'// {p.get("label",k)}{unit}: {p["doc"]}')
    Path(path).write_text('\n'.join(lines)+'\n')


if __name__=='__main__':
    write_scad();print(f'wrote params.scad ({len(specs())} parameters)')
    sys.exit(0)
